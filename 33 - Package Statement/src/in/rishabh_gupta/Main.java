/*
 * Package Statement
 * It is  an encapsulation mechanism to group related classes and interfaces into a single unit which is nothing but package
 * examples
 * - all classes and interfaces which are required for database operations are grouped into a single package which is nothing but java.sql package
 * - all classes and interfaces which are required for file operations are grouped into a single package which is nothing but java.io package
 * The main advantages of packages are
 * - to resolve naming conflicts
 * - it improves modularity of the application
 * - it improves maintainability of the application
 * - There is one universally accepted naming convention i.e. to use internet domain name in reverse order
 */
