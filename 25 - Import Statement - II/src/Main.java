import java.util.ArrayList;

/*
 * Import Statement - II
 *
 * - Using the fully qualified name (e.g., java.util.ArrayList) every time
 *   makes the code lengthy and less readable.
 * - By writing an import statement, we can directly use the class name
 *   without its package prefix.
 * - This improves readability and reduces boilerplate.
 */
public class Main {
    public static void main(String[] args) {
        ArrayList arrayList = new ArrayList();
    }
}
